"""One arm's URDF: the vendored Maker Arm chain with the stock gripper replaced by the
rotating toolhead, a frame per tool tip and the wrist camera's optical frame."""

from __future__ import annotations

import os
import xml.etree.ElementTree as ET
from pathlib import Path

from .config import ArmCalibration, ArmConfig, Pose, check_calibration
from .vendor import ARM_JOINTS, GRIPPER_JOINTS, GRIPPER_LINKS, VENDOR_URDF, WRIST_LINK

FLANGE_LINK = "flange"
TOOLHEAD_LINK = "toolhead_link"
TOOLHEAD_JOINT = "toolhead_joint"
CAMERA_LINK = "wrist_camera_optical"


def tool_link(tool: str) -> str:
    return f"tool_{tool}"


def prefixed(config: ArmConfig, name: str) -> str:
    """Link or joint name as it appears in this arm's URDF."""
    return f"{config.name}_{name}"


def build_urdf(
    config: ArmConfig,
    calibration: ArmCalibration | None = None,
    output_dir: str | Path = ".",
    vendor_urdf: Path = VENDOR_URDF,
) -> tuple[str | None, list[str]]:
    """URDF text with mesh paths relative to output_dir, or None and the problems."""
    problems = [f"unconfigured:{key}" for key in config.missing_for_urdf()]
    problems += check_calibration(config, calibration)
    if problems:
        return None, problems

    robot = ET.parse(vendor_urdf).getroot()
    for element in list(robot):
        if element.get("name") in (GRIPPER_LINKS if element.tag == "link" else GRIPPER_JOINTS):
            robot.remove(element)

    wrist = robot.find(f"link[@name='{WRIST_LINK}']")
    present = {mesh.get("filename") for mesh in wrist.iter("mesh")}
    unknown = sorted(set(config.remove_link_007_meshes) - present)
    if unknown:
        return None, [
            f"invalid:arm.remove_link_007_meshes ({', '.join(unknown)} not on {WRIST_LINK})"
        ]
    for element in list(wrist):
        mesh = element.find("geometry/mesh")
        if mesh is not None and mesh.get("filename") in config.remove_link_007_meshes:
            wrist.remove(element)

    output_dir = Path(output_dir).resolve()
    for mesh in robot.iter("mesh"):
        mesh.set("filename", _mesh_path(vendor_urdf.parent / mesh.get("filename"), output_dir))

    calibration_tips = calibration.tool_tips if calibration else {}
    camera = calibration.wrist_camera if calibration and calibration.wrist_camera else None
    calibrated = (["wrist_camera"] if camera else []) + [
        f"tool_{name}.tip" for name in sorted(calibration_tips)
    ]
    nominal = (["wrist_camera"] if not camera else []) + [
        f"tool_{tool.name}.tip" for tool in config.tools if tool.name not in calibration_tips
    ]

    _fixed(robot, "flange_joint", WRIST_LINK, FLANGE_LINK, config.flange)

    toolhead = ET.SubElement(robot, "link", name=TOOLHEAD_LINK)
    mesh_path = _mesh_path(config.toolhead_mesh, output_dir)
    scale = " ".join(f"{v:.9g}" for v in config.toolhead_mesh_scale)
    for tag in ("visual", "collision"):
        geometry = ET.SubElement(ET.SubElement(toolhead, tag), "geometry")
        ET.SubElement(geometry, "mesh", filename=mesh_path, scale=scale)

    joint = ET.SubElement(robot, "joint", name=TOOLHEAD_JOINT, type="revolute")
    _origin(joint, config.toolhead_origin)
    ET.SubElement(joint, "parent", link=FLANGE_LINK)
    ET.SubElement(joint, "child", link=TOOLHEAD_LINK)
    ET.SubElement(joint, "axis", xyz=" ".join(f"{v:.9g}" for v in config.toolhead_axis))
    # Motor 7 is the same RS00 as J6, so its effort/velocity entries are reused. They are
    # upstream placeholders; the SDK profile, not the URDF, limits the real motor.
    wrist_limit = robot.find(f"joint[@name='{ARM_JOINTS[-1]}']/limit")
    ET.SubElement(
        joint,
        "limit",
        lower=f"{config.toolhead_lower_rad:.9g}",
        upper=f"{config.toolhead_upper_rad:.9g}",
        effort=wrist_limit.get("effort"),
        velocity=wrist_limit.get("velocity"),
    )

    for tool in config.tools:
        tip = calibration_tips.get(tool.name, tool.tip)
        _fixed(robot, f"{tool_link(tool.name)}_joint", TOOLHEAD_LINK, tool_link(tool.name), tip)
    _fixed(robot, "wrist_camera_joint", WRIST_LINK, CAMERA_LINK, camera or config.wrist_camera)

    _prefix(robot, config.name)
    robot.set("name", f"maker_arm_{config.name}")
    notes = [
        f"Generated by hardware_troubleshooter_arm for arm {config.name!r}. Don't edit by hand.",
        f"Calibration: {calibration.calibration_id if calibration else 'none'}.",
        f"Calibrated: {', '.join(calibrated) or 'nothing'}.",
        f"Nominal CAD values: {', '.join(nominal) or 'none'}.",
    ]
    for i, note in enumerate(notes):
        robot.insert(i, ET.Comment(f" {note} "))
    ET.indent(robot)
    return '<?xml version="1.0"?>\n' + ET.tostring(robot, encoding="unicode") + "\n", []


def _fixed(robot: ET.Element, name: str, parent: str, child: str, pose: Pose) -> None:
    ET.SubElement(robot, "link", name=child)
    joint = ET.SubElement(robot, "joint", name=name, type="fixed")
    _origin(joint, pose)
    ET.SubElement(joint, "parent", link=parent)
    ET.SubElement(joint, "child", link=child)


def _origin(element: ET.Element, pose: Pose) -> None:
    xyz, rpy = pose
    ET.SubElement(
        element,
        "origin",
        xyz=" ".join(f"{v:.9g}" for v in xyz),
        rpy=" ".join(f"{v:.9g}" for v in rpy),
    )


def _prefix(robot: ET.Element, name: str) -> None:
    for element in robot:
        if element.tag in ("link", "joint"):
            element.set("name", f"{name}_{element.get('name')}")
        for ref in element.findall("parent") + element.findall("child"):
            ref.set("link", f"{name}_{ref.get('link')}")
        for mimic in element.findall("mimic"):
            mimic.set("joint", f"{name}_{mimic.get('joint')}")


def _mesh_path(path: Path, output_dir: Path) -> str:
    path = Path(path).resolve()
    try:
        return Path(os.path.relpath(path, output_dir)).as_posix()
    except ValueError:  # different drive on Windows
        return path.as_posix()
