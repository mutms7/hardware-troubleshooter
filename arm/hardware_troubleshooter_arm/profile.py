"""Maker SDK profile for an arm with the rotating toolhead.

J1..J6 and the bus settings are copied from the vendored maker_arm_v1 profile. Motor 7
keeps its motor model and ID; its direction, offset, limits and gains are replaced,
because the stock entry is tuned soft on purpose for a compliant gripper."""

from __future__ import annotations

from pathlib import Path

import yaml

from .config import SDK7_KEYS, ArmConfig
from .vendor import TOOLHEAD_MOTOR_ID, VENDOR_PROFILE

# Ranges the SDK's ArmConfig._validate enforces (maker_arm/protocol.py).
KP_RANGE = (0.0, 500.0)
KD_RANGE = (0.0, 5.0)
MOTOR_POSITION_RANGE = (-12.57, 12.57)


def build_sdk_profile(
    config: ArmConfig, vendor_profile: Path = VENDOR_PROFILE
) -> tuple[dict | None, list[str]]:
    problems = [f"unconfigured:{key}" for key in config.missing_for_sdk_profile()]
    if problems:
        return None, problems

    profile = yaml.safe_load(Path(vendor_profile).read_text(encoding="utf-8"))
    entries = [j for j in profile["joints"] if j["motor_id"] == TOOLHEAD_MOTOR_ID]
    if len(entries) != 1:
        return None, [f"invalid:vendor_profile (expected one motor {TOOLHEAD_MOTOR_ID} entry)"]
    entry = entries[0]
    joint7 = config.sdk_joint7
    entry.update({key: getattr(joint7, key) for key in SDK7_KEYS})

    margin = float(profile.get("limit_margin", 0.0))
    if not joint7.lo + 2 * margin < joint7.hi:
        problems.append("invalid:arm.sdk_joint7 (needs lo + 2 * limit_margin < hi)")
    if not KP_RANGE[0] <= joint7.kp <= KP_RANGE[1]:
        problems.append(f"invalid:arm.sdk_joint7.kp (must be within {KP_RANGE})")
    if not KD_RANGE[0] <= joint7.kd <= KD_RANGE[1]:
        problems.append(f"invalid:arm.sdk_joint7.kd (must be within {KD_RANGE})")
    for limit in (joint7.lo, joint7.hi):
        motor = limit * joint7.direction + joint7.offset
        if not MOTOR_POSITION_RANGE[0] <= motor <= MOTOR_POSITION_RANGE[1]:
            problems.append(
                f"invalid:arm.sdk_joint7 (limit {limit} maps to motor {motor:.3f} rad, "
                f"outside the encoder range {MOTOR_POSITION_RANGE})"
            )
    if problems:
        return None, problems
    return profile, []


def dump_sdk_profile(config: ArmConfig, profile: dict) -> str:
    header = (
        f"# Generated by hardware_troubleshooter_arm for arm {config.name!r}. Don't edit by hand.\n"
        f"# J1-J6 and bus settings: vendored maker_arm_v1. Motor {TOOLHEAD_MOTOR_ID}: rotating "
        "toolhead, from arm.sdk_joint7.\n"
        "# Pass it to the SDK with --config, or Arm.from_yaml(path).\n"
    )
    return header + yaml.safe_dump(profile, sort_keys=False)
