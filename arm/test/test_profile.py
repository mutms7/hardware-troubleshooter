import pytest
import yaml
from arm_synthetic import SYNTHETIC_ARM
from hardware_troubleshooter_arm.build import main
from hardware_troubleshooter_arm.profile import build_sdk_profile, dump_sdk_profile
from hardware_troubleshooter_arm.vendor import VENDOR_PROFILE


def test_only_motor_7_changes(arm):
    vendor = yaml.safe_load(VENDOR_PROFILE.read_text(encoding="utf-8"))
    profile, problems = build_sdk_profile(arm)
    assert not problems
    assert profile["joints"][:6] == vendor["joints"][:6]
    assert {k: v for k, v in profile.items() if k != "joints"} == {
        k: v for k, v in vendor.items() if k != "joints"
    }
    joint7 = profile["joints"][6]
    assert joint7["motor_id"] == 7 and joint7["model"] == "RS00"
    assert (joint7["lo"], joint7["hi"], joint7["kp"], joint7["kd"]) == (-2.5, 2.5, 120, 3.0)


def test_dumped_profile_round_trips(arm):
    profile, _ = build_sdk_profile(arm)
    text = dump_sdk_profile(arm, profile)
    assert text.startswith("# Generated by hardware_troubleshooter_arm for arm 'left'")
    assert yaml.safe_load(text) == profile


@pytest.mark.parametrize(
    "change, expected",
    [
        ({"kp": 600}, "invalid:arm.sdk_joint7.kp"),
        ({"kd": 6}, "invalid:arm.sdk_joint7.kd"),
        ({"lo": 2.5, "hi": 2.5}, "needs lo + 2 * limit_margin < hi"),
        ({"offset": 11.0}, "outside the encoder range"),
    ],
)
def test_out_of_range_values_are_rejected(make_arm, change, expected):
    config, problems = make_arm(sdk_joint7={**SYNTHETIC_ARM["sdk_joint7"], **change})
    assert not problems
    profile, problems = build_sdk_profile(config)
    assert profile is None
    assert any(expected in p for p in problems), problems


def test_unset_joint7_fails_closed(make_arm):
    config, _ = make_arm(sdk_joint7={**SYNTHETIC_ARM["sdk_joint7"], "kp": None})
    assert build_sdk_profile(config) == (None, ["unconfigured:arm.sdk_joint7.kp"])


def test_sdk_accepts_the_profile(arm, tmp_path):
    sdk_config = pytest.importorskip("maker_arm.config")
    profile, _ = build_sdk_profile(arm)
    path = tmp_path / "profile.yaml"
    path.write_text(dump_sdk_profile(arm, profile), encoding="utf-8")
    assert sdk_config.ArmConfig.from_yaml(str(path)).n_joints == 7


def test_build_cli(arm_dir, tmp_path, capsys):
    config_path = arm_dir / "left.yaml"
    config_path.write_text(yaml.safe_dump(SYNTHETIC_ARM))
    out = tmp_path / "out"
    assert main([str(config_path), "--out", str(out)]) == 0
    assert (out / "left.urdf").is_file()
    assert (out / "left_sdk_profile.yaml").is_file()


def test_build_cli_reports_unset_values(tmp_path, capsys):
    from pathlib import Path

    example = Path(__file__).resolve().parents[1] / "config" / "arm.example.yaml"
    assert main([str(example), "--out", str(tmp_path / "out")]) == 1
    assert "unconfigured:arm.name" in capsys.readouterr().err
    assert not (tmp_path / "out").exists()
